/**
 * Returns an inline SVG string with specific size and optional CSS class.
 * @param {string} name - Name of icon from ICONS catalog
 * @param {number} size - Width & height in pixels (default 18)
 * @param {string} className - Optional CSS class
 * @returns {string}
 */
export function getIconSvg(name, size = 18, className = 'icon-svg') {
  const raw = ICONS[name] || ICONS.globe;
  return raw
    .trim()
    .replace('<svg', `<svg width="${size}" height="${size}" class="${className}" style="display: inline-block; vertical-align: middle; flex-shrink: 0;" aria-hidden="true"`);
}
